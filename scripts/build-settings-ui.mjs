/**
 * 設定ウィンドウ用 JavaScript を esbuild で IIFE バンドルする
 *
 * 出力は Rust の `include_str!` で埋め込む。`cargo build` 単体では Node を要求しないため、
 * 生成物 `settings.bundle.js` はリポジトリにコミットする。
 * `check.ps1` は再生成後に未ステージ差分が残っていないことを検証する
 */
import * as esbuild from 'esbuild';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const entry = join(root, 'crates/clip-refiner/src/ui/settings/main.js');
const outfile = join(root, 'crates/clip-refiner/src/ui/settings/settings.bundle.js');

await esbuild.build({
    absWorkingDir: root,
    entryPoints: [entry],
    outfile,
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: ['es2022'],
    // 埋め込み後のデバッグと Rust 側の文字列アサーション用に圧縮しない
    minify: false,
    // 日本語ラベルを \uXXXX にせず UTF-8 のまま出力する
    charset: 'utf8',
    sourcemap: false,
    logLevel: 'info',
    banner: {
        js: '/* Generated by scripts/build-settings-ui.mjs — do not edit */',
    },
});

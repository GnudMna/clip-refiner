/**
 * 設定ウィンドウ / セレクター用 JavaScript を esbuild で IIFE バンドルする
 *
 * 出力は Rust の `include_str!` で埋め込む。`cargo build` 単体では Node を要求しないため、
 * 生成物 `*.bundle.js` はリポジトリにコミットする。
 * `check.ps1` は再生成後に未ステージ差分が残っていないことを検証する
 */
import * as esbuild from 'esbuild';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const uiRoot = join(root, 'crates/clip-refiner/src/ui');

/** @type {ReadonlyArray<{ entry: string, outfile: string }>} */
const bundles = [
    {
        entry: join(uiRoot, 'settings/main.js'),
        outfile: join(uiRoot, 'settings/settings.bundle.js'),
    },
    {
        entry: join(uiRoot, 'quick_selector.js'),
        outfile: join(uiRoot, 'quick_selector.bundle.js'),
    },
    {
        entry: join(uiRoot, 'clip_selector.js'),
        outfile: join(uiRoot, 'clip_selector.bundle.js'),
    },
];

/** @type {import('esbuild').BuildOptions} */
const shared = {
    absWorkingDir: root,
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: ['es2022'],
    // 埋め込み後のデバッグと Rust 側の文字列アサーション用に圧縮しない
    minify: false,
    // 日本語ラベルを \uXXXX にせず UTF-8 のまま出力する
    charset: 'utf8',
    sourcemap: false,
    logLevel: 'info',
    banner: {
        js: '/* Generated by scripts/common/build-ui.mjs — do not edit */',
    },
};

for (const { entry, outfile } of bundles) {
    await esbuild.build({
        ...shared,
        entryPoints: [entry],
        outfile,
    });
}

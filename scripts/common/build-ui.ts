/**
 * 設定ウィンドウ / セレクター用 TypeScript を esbuild で IIFE バンドルする
 *
 * 出力は Rust の `include_str!` で埋め込む。`cargo build` 単体では Node を要求しないため、
 * 生成物 `*.bundle.js` はリポジトリにコミットする
 *
 * 生成物の先頭には入力ファイル一覧とその SHA-256 を刻む。Rust の統合テスト
 * (`tests/flow/ui_bundle.rs`) が Node なしで同じハッシュを再計算し、ソースだけ更新して
 * バンドルを忘れたコミットを検出する
 *
 * `--check` を付けると書き込まずに再生成結果と既存ファイルを比較し、差分があれば終了コード 1 を返す
 * (`check.ps1` が使う。手編集や esbuild の版差もここで検出する)
 */
import * as esbuild from 'esbuild';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const uiRoot = join(root, 'crates/clip-refiner/src/ui');
const checkOnly = process.argv.includes('--check');

/** ビルド設定自体も出力に影響するため入力として扱う */
const buildScript = relative(root, fileURLToPath(import.meta.url)).replaceAll('\\', '/');

const bundles: ReadonlyArray<{ entry: string; outfile: string }> = [
    {
        entry: join(uiRoot, 'settings/main.ts'),
        outfile: join(uiRoot, 'settings/settings.bundle.js'),
    },
    {
        entry: join(uiRoot, 'selector/quick_selector.ts'),
        outfile: join(uiRoot, 'selector/quick_selector.bundle.js'),
    },
    {
        entry: join(uiRoot, 'selector/clip_selector.ts'),
        outfile: join(uiRoot, 'selector/clip_selector.bundle.js'),
    },
];

const shared = {
    absWorkingDir: root,
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: ['es2024'],
    // tsconfig.json は入力ハッシュに含まれないため、出力に影響する設定をここで固定する
    tsconfigRaw: { compilerOptions: { strict: true, verbatimModuleSyntax: true } },
    // 埋め込み後のデバッグと Rust 側の文字列アサーション用に圧縮しない
    minify: false,
    // 日本語ラベルを \uXXXX にせず UTF-8 のまま出力する
    charset: 'utf8',
    sourcemap: false,
    logLevel: 'warning',
    metafile: true,
    write: false,
} satisfies esbuild.BuildOptions;

/**
 * 入力ファイル群の SHA-256 を求める
 *
 * Rust 側 (`tests/flow/ui_bundle.rs`) と同じ手順: パス昇順に `パス \0 内容 \0` を連結してハッシュする
 *
 * @param inputs - ルート相対の `/` 区切りパス (昇順)
 * @returns 小文字 16 進
 */
async function hashInputs(inputs: ReadonlyArray<string>): Promise<string> {
    const hash = createHash('sha256');
    for (const input of inputs) {
        hash.update(input);
        hash.update('\0');
        hash.update(await readFile(join(root, input)));
        hash.update('\0');
    }
    return hash.digest('hex');
}

/**
 * 1 バンドル分の生成物を組み立てる
 */
async function renderBundle(entry: string): Promise<string> {
    const result = await esbuild.build({ ...shared, entryPoints: [entry], outfile: 'out.js' });
    const { metafile, outputFiles } = result;
    if (!metafile || !outputFiles?.[0]) {
        throw new Error(`esbuild の出力が得られませんでした: ${entry}`);
    }
    const inputs = [...Object.keys(metafile.inputs), buildScript].sort();
    const header = [
        '/* Generated by scripts/common/build-ui.ts — do not edit */',
        `/* inputs-sha256: ${await hashInputs(inputs)} */`,
        ...inputs.map((input) => `/* input: ${input} */`),
    ].join('\n');
    return `${header}\n${outputFiles[0].text}`;
}

/**
 * 既存ファイルを読む (無ければ `null`)
 */
async function readExisting(path: string): Promise<string | null> {
    try {
        return await readFile(path, 'utf8');
    } catch (error) {
        if (error instanceof Error && 'code' in error && error.code === 'ENOENT') {
            return null;
        }
        throw error;
    }
}

const stale = [];
for (const { entry, outfile } of bundles) {
    const content = await renderBundle(entry);
    const displayPath = relative(root, outfile).replaceAll('\\', '/');
    if (checkOnly) {
        if ((await readExisting(outfile)) !== content) {
            stale.push(displayPath);
        }
        continue;
    }
    await writeFile(outfile, content);
    console.log(`  ${displayPath}`);
}

if (stale.length > 0) {
    console.error('エラー: UI バンドルがソースと同期していません:');
    for (const path of stale) {
        console.error(`  ${path}`);
    }
    console.error('');
    console.error('再生成してコミットしてください: npm run build:ui');
    process.exit(1);
}
